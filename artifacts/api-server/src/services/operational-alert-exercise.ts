import assert from "node:assert/strict";
import { auditTable,db,operationalAlertsTable } from "@workspace/db";
import { eq } from "drizzle-orm";
import type { CommandAction } from "@workspace/deal-domain";
import { listOperationalAlerts,updateOperationalAlert } from "./operational-alerts";
const now=new Date("2026-10-16T12:00:00Z");
const make=(id:string,priority:number):CommandAction=>({id,category:"DEADLINE",priority,title:`Alert ${id}`,reason:"Persisted deadline needs review",leadId:"synthetic-lead",href:"/leads/synthetic-lead",cta:"Review",dueAt:now.toISOString(),workGuidance:null});
const low=make("alert-low",20),high=make("alert-high",90);
let rows=await listOperationalAlerts([low,high],now);
assert.deepEqual(rows.map(r=>r.alertKey),["alert-high","alert-low"],"priority ordering uses persisted source priority");
rows=await listOperationalAlerts([low,high],now);
assert.equal(rows.length,2,"repeat source sync deduplicates alert records");
const alert=rows.find(r=>r.alertKey===low.id)!;
await assert.rejects(updateOperationalAlert(alert.id,"DISMISS",{id:"analyst",role:"ANALYST"},undefined,now),/Only owners and operators/);
await updateOperationalAlert(alert.id,"SNOOZE",{id:"operator",role:"OPERATOR"},new Date(now.getTime()+60_000),now);
assert.equal((await listOperationalAlerts([low,high],now)).length,1,"snoozed alert is hidden but retained");
rows=await listOperationalAlerts([low,high],new Date(now.getTime()+61_000));
assert.equal(rows.length,2,"expired snooze reactivates alert");
await updateOperationalAlert(alert.id,"DISMISS",{id:"owner",role:"OWNER"},undefined,new Date(now.getTime()+61_000));
assert.equal((await listOperationalAlerts([low,high],new Date(now.getTime()+62_000))).length,1,"dismissed alert stays dismissed while actionable");
await listOperationalAlerts([high],new Date(now.getTime()+63_000));
const [resolved]=await db.select().from(operationalAlertsTable).where(eq(operationalAlertsTable.alertKey,low.id));
assert.equal(resolved?.status,"RESOLVED","disappearing source action resolves its alert");
assert.ok((await db.select().from(auditTable)).some(e=>e.action==="OPERATIONAL_ALERT_SNOOZE"||e.action==="OPERATIONAL_ALERT_DISMISS"));
const analystAction={...make("analyst-alert",60),workGuidance:{responsibleRole:"ANALYST"} as CommandAction["workGuidance"]};
const allRoleAlerts=await listOperationalAlerts([high,analystAction],new Date(now.getTime()+64_000),"OWNER");
const analystAlerts=await listOperationalAlerts([high,analystAction],new Date(now.getTime()+65_000),"ANALYST");
assert.ok(allRoleAlerts.some(r=>r.alertKey==="analyst-alert"));
assert.deepEqual(analystAlerts.map(r=>r.alertKey),["analyst-alert"],"read access is scoped to the assigned role while owner can review all");
console.log("Persisted operational alert exercise passed: dedupe, priority, snooze expiry, permissions, dismissal, source resolution, audit; no outbound delivery path.");
